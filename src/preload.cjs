  onProductivityConfirmation:callback=>listen('productivity:confirmation',callback),
  onNotch:callback=>listen('notch:state',callback),
  setReminderHud:on=>ipcRenderer.invoke('window:reminder-hud',!!on),
  onProductivity:callback=>listen('productivity:changed',callback),
  onProductivityOpen:callback=>listen('productivity:open',callback),
  onProductivityDiagnostic:callback=>listen('productivity:diagnostic',callback),
  save: value => ipcRenderer.invoke('state:save', value),
  savedProviderKeys:()=>ipcRenderer.invoke('settings:keys'),
